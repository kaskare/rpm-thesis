"""## 7. Template (GNN)

- **object_emb** — one rule per `(type, size, color, pos)` combination; the conjunction body fires only for objects that have all four values simultaneously, giving each unique object configuration its own learned embedding vector directly — no intermediate per-attribute embeddings
- **h1, h2, h3** — 3 GNN layers over all edge types (spatial + same_pos)
- **Scoring** — pool h3 and object_emb of candidate objects
"""

def _add_gnn_layer(template, h_out, h_in, D, edge_rels):
    """One GNN layer: message passing along each edge type + self-connection (skip)."""
    for rel in edge_rels:
        template += R.get(h_out)(V.X) <= (
            R.get(h_in)(V.X)[D, D],
            R.get(h_in)(V.Y)[D, D],
            R.get(rel)(V.X, V.Y),
        )
    template += R.get(h_out)(V.X) <= R.get(h_in)(V.X)[D, D]   # skip / residual


def build_template(D=EMBED_DIM):
    template  = Template()
    edge_rels = SPATIAL_RELS + ['same_pos']

    # ── object embedding via numeric features ────────────────────────────
    template += R.object_emb(V.X)[D, 4] <= R.node_feature(V.X)

    # ── GNN layers ───────────────────────────────────────────────────────
    _add_gnn_layer(template, 'h1', 'object_emb', D, edge_rels)
    _add_gnn_layer(template, 'h2', 'h1',         D, edge_rels)
    _add_gnn_layer(template, 'h3', 'h2',         D, edge_rels)

    # ── Scoring head ─────────────────────────────────────────────────────
    template += R.predict[1, D] <= (R.h3(V.X),         R.is_cand(V.X))
    template += R.predict[1, D] <= (R.object_emb(V.X), R.is_cand(V.X))

    return template


