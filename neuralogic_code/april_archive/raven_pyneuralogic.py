"""## 5. Graph (sub-graph) construction

One sub-graph per candidate: 8 context panels + 1 candidate panel.

Three edge families:
1. **Intra-panel spatial** — 6 relations between all object pairs within a panel (O(n²), n≤9)
2. **`same_pos`** — connects objects at the same universal position across any two panels
3. **Cross-panel spatial** — directional edges between objects in grid-adjacent panels
"""

def _infer_spatial_rels(sx, sy, dx, dy, eps=1e-4):
    rels = []
    if   sx < dx - eps: rels.append('left_of')
    elif sx > dx + eps: rels.append('right_of')
    if   sy < dy - eps: rels.append('above')
    elif sy > dy + eps: rels.append('below')
    if abs(sy - dy) <= eps: rels.append('same_row')
    if abs(sx - dx) <= eps: rels.append('same_col')
    return rels


def _global_pos(panel_idx, pos):
    r, c = PANEL_TO_COORD[panel_idx]
    lx, ly = POS_CENTERS.get(pos, (0.0, 0.0))
    return (c * PANEL_SPACING + lx, r * PANEL_SPACING + ly)


def _nid(panel, pos):
    return f'p{panel}_o{pos}'


def build_subgraph(obj_type, obj_size, obj_color, obj_exists, cand_idx):
    facts       = []
    cand_panel  = NUM_CONTEXT + cand_idx
    active      = list(range(NUM_CONTEXT)) + [cand_panel]

    # ── Collect nodes per panel & emit feature facts ─────────────────────────
    panel_nodes = {}   # panel → [(pos, node_id), ...]
    for panel in active:
        pnodes = []
        for pos in range(NUM_POSITIONS):
            if not obj_exists[panel, pos]:
                continue

            n = _nid(panel, pos)

            t = int(obj_type[panel, pos])
            s = int(obj_size[panel, pos])
            c = int(obj_color[panel, pos])
            p = pos

            feature = [
                t / NUM_SHAPE,
                s / NUM_SIZE,
                c / NUM_COLOR,
                p / NUM_POSITIONS,
            ]

            # single fact instead of 4 attribute predicates
            facts.append(R.node_feature(n)[feature])

            pnodes.append((pos, n))

        panel_nodes[panel] = pnodes

    # ── Intra-panel spatial edges ─────────────────────────────────────────
    for panel in active:
        nodes = panel_nodes[panel]
        for i, (pi, ni) in enumerate(nodes):
            for j, (pj, nj) in enumerate(nodes):
                if i == j:
                    continue
                sx, sy = POS_CENTERS[pi]
                dx, dy = POS_CENTERS[pj]
                for rel in _infer_spatial_rels(sx, sy, dx, dy):
                    facts.append(R.get(rel)(ni, nj))

    # ── same_pos cross-panel edges ────────────────────────────────────────
    for pos in range(NUM_POSITIONS):
        at_pos = [n for panel in active
                  for p, n in panel_nodes[panel] if p == pos]
        for i in range(len(at_pos)):
            for j in range(i + 1, len(at_pos)):
                facts.append(R.same_pos(at_pos[i], at_pos[j]))
                facts.append(R.same_pos(at_pos[j], at_pos[i]))

    # ── Cross-panel spatial edges (grid-adjacent panels only) ─────────────
    coord_to_panels = {}
    for p in active:
        coord_to_panels.setdefault(PANEL_TO_COORD[p], []).append(p)

    for (r, c), panels_here in coord_to_panels.items():
        for nr, nc in [(r, c + 1), (r + 1, c)]:
            for q in coord_to_panels.get((nr, nc), []):
                for p in panels_here:
                    for pi, ni in panel_nodes[p]:
                        gxi, gyi = _global_pos(p, pi)
                        for pj, nj in panel_nodes[q]:
                            gxj, gyj = _global_pos(q, pj)
                            for rel in _infer_spatial_rels(gxi, gyi, gxj, gyj):
                                facts.append(R.get(rel)(ni, nj))
                            for rel in _infer_spatial_rels(gxj, gyj, gxi, gyi):
                                facts.append(R.get(rel)(nj, ni))

    # ── Mark candidate objects ────────────────────────────────────────────
    for _, n in panel_nodes[cand_panel]:
        facts.append(R.is_cand(n))

    return facts


print('Graph builder ready ✓')

"""## 6. Dataset construction"""

def build_dataset(samples, oversample_pos=1):
    """
    One sub-graph per (RPM, candidate) pair.
    oversample_pos: repeat correct-candidate examples this many times.
    """
    ds = Dataset()
    for obj_type, obj_size, obj_color, obj_exists, target in samples:
        for ci in range(NUM_CANDIDATES):
            facts   = build_subgraph(obj_type, obj_size, obj_color, obj_exists, ci)
            label   = 1.0 if ci == target else 0.0
            repeats = oversample_pos if ci == target else 1
            for _ in range(repeats):
                ds.add_example(facts)
                ds.add_query(R.predict[label])
    return ds


