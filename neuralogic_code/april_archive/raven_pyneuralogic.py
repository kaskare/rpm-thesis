"""## 9. Evaluation"""

def evaluate(evaluator, samples, label='test'):
    """Score 8 sub-graphs per RPM, pick argmax, return (correct, total)."""
    ds    = build_dataset(samples, oversample_pos=1)
    built = evaluator.build_dataset(ds)
    preds = list(evaluator.test(built))
    correct = sum(
        int(np.argmax(preds[i*8:(i+1)*8])) == samples[i][4]
        for i in range(len(samples))
    )
    return correct, len(samples)


